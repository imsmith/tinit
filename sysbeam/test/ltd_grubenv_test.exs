defmodule Sysbeam.Ltd.GrubenvTest do
  use ExUnit.Case
  alias Sysbeam.Ltd.Grubenv

  setup do
    path = Path.join(System.tmp_dir!(), "grubenv-#{System.unique_integer([:positive])}")
    on_exit(fn -> File.rm(path) end)
    {:ok, path: path}
  end

  test "writes GRUB's 1024-byte block and reads it back", %{path: path} do
    assert :ok = Grubenv.write(path, %{"cmdline" => "console=ttyS0 quiet"})
    assert {:ok, %{"cmdline" => "console=ttyS0 quiet"}} = Grubenv.read(path)
    assert byte_size(File.read!(path)) == 1024
    assert File.read!(path) =~ ~r/^# GRUB Environment Block\ncmdline=console=ttyS0 quiet\n#+$/
  end

  test "reads a block grub-editenv wrote, comments skipped", %{path: path} do
    body = "# GRUB Environment Block\n# WARNING: Do not edit this file by tools other than grub-editenv!!!\ncmdline=a b\ndefault=0\n"
    File.write!(path, body <> String.duplicate("#", 1024 - byte_size(body)))
    assert {:ok, %{"cmdline" => "a b", "default" => "0"}} = Grubenv.read(path)
  end

  test "a value that does not fit is refused, not truncated", %{path: path} do
    assert {:error, :too_long} = Grubenv.write(path, %{"cmdline" => String.duplicate("x", 1000)})
    refute File.exists?(path)
  end

  test "a missing block is an error the caller can see", %{path: path} do
    assert {:error, :enoent} = Grubenv.read(path)
  end
end
